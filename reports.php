mysqli_query($conn, $active_logs_query);

$active_logs =
mysqli_fetch_assoc($active_logs_result);


/* CHART DATA */

$chart_query =
"SELECT protocol, COUNT(*) AS total
 FROM traffic_logs
 GROUP BY protocol";

$chart_result =
mysqli_query($conn, $chart_query);

